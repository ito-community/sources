const PASSES: [Pass; 3] = [
    Pass { table: &TABLE_1, key: &KEY_1, seed: 90 },
    Pass { table: &TABLE_2, key: &KEY_2, seed: 53 },
    Pass { table: &TABLE_3, key: &KEY_3, seed: 186 },
];

/// Returns the `vrf` value for a canonical request string.
pub fn sign(canonical: &str) -> String {
    let mut data = canonical.as_bytes().to_vec();
    for pass in &PASSES {
        let mut previous = pass.seed;
        for (index, byte) in data.iter_mut().enumerate() {
            let key_byte = pass.key[index % pass.key.len()];
            let output = pass.table[usize::from(*byte ^ key_byte ^ previous)];
            *byte = output;
            previous = output;
        }
    }
    URL_SAFE_NO_PAD.encode(data)
}

