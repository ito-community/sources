//! Request signing for the `/api` endpoints.
//!
//! The site requires a `vrf` query parameter on `/titles...` and `/chapters/...` requests. The
//! value is a function of the canonical request string only: the API path (without the `/api`
//! prefix) followed by `?` and the query parameters sorted by top-level parameter name, with array
//! and object parameters flattened to `name[index]` / `name[key]` and values left unescaped.
//!
//! The canonical string is encoded as UTF-8 and passed through three keyed byte-substitution
//! passes. Each pass XORs a byte with the pass key (repeating) and with the previous output byte
//! of the same pass, then looks the result up in a 256-entry permutation table. The final bytes
//! are written as URL-safe base64 without padding.

